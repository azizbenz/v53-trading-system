"""Mini profile harness for _feature_overlay_batch_from_engine_native_bridge bottleneck.

Reuses silver/* files already generated by the cancelled run
strategy_ladder_workflow-53b96767bddb7e05 to reproduce the
A2 gold microstructure bottleneck on a controlled scope (60 decision rows = 1h).
"""

from __future__ import annotations

import cProfile
import pstats
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = REPO_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from local_replay_runtime.strategy_ladder_data_factory import (  # noqa: E402
    _feature_overlay_batch_from_engine_native_bridge,
)
from local_replay_runtime.strategy_ladder_data_factory_models import (  # noqa: E402
    StrategyLadderSilverIndexEntry,
)
from local_replay_runtime.strategy_ladder_engine_native_adapter import (  # noqa: E402
    get_microstructure_file_cache_stats,
    reset_microstructure_file_cache_stats,
)


SILVER_ROOT = Path(
    r"L:\output backtest\runs\strategy_ladder_workflow-53b96767bddb7e05\phase_a2_data_factory\silver\bybit\spot"
)
TRADES_PATH = SILVER_ROOT / "trades" / "BTCUSDT" / "2025" / "07" / "08.jsonl.gz"
BOOK_SNAPSHOT_PATH = SILVER_ROOT / "orderbook_snapshot" / "BTCUSDT" / "2025" / "07" / "08.jsonl.gz"
BOOK_DELTA_PATH = SILVER_ROOT / "orderbook_delta" / "BTCUSDT" / "2025" / "07" / "08.jsonl.gz"

# 2025-07-08 00:00:00 UTC in ms
START_MS = 1751932800000


def _make_silver_entry(*, data_type: str, path: Path) -> StrategyLadderSilverIndexEntry:
    return StrategyLadderSilverIndexEntry(
        source_id="profile_test",
        source_root=str(path.parent.parent.parent.parent.parent),
        source_priority=0,
        exchange="bybit",
        market_type="spot",
        data_type=data_type,
        pair="BTCUSDT",
        timeframe="",
        date="2025-07-08",
        path=str(path),
        storage_format="jsonl_gz",
        min_timestamp_ms=START_MS,
        max_timestamp_ms=START_MS + 24 * 60 * 60 * 1000,
        row_count=0,
        depth_source_status="BOOK_DEPTH20_AVAILABLE",
        schema_status="SCHEMA_READY",
    )


def _make_decision_rows(count: int = 60) -> list[dict[str, object]]:
    """Build N decision rows spanning N minutes (one per minute)."""
    return [
        {
            "timestamp_ms": START_MS + i * 60_000,
            "open": 100_000.0,
            "high": 100_500.0,
            "low": 99_500.0,
            "close": 100_200.0,
            "volume": 10.0,
        }
        for i in range(count)
    ]


def run_profile(*, row_count: int = 60, features: tuple[str, ...] = ("vpin",)) -> None:
    if not TRADES_PATH.exists():
        print(f"FATAL: missing trades file {TRADES_PATH}", file=sys.stderr)
        sys.exit(2)
    if not BOOK_DELTA_PATH.exists():
        print(f"FATAL: missing book_delta file {BOOK_DELTA_PATH}", file=sys.stderr)
        sys.exit(2)

    trade_entries = (_make_silver_entry(data_type="trades", path=TRADES_PATH),)
    book_entries = (
        _make_silver_entry(data_type="orderbook_snapshot", path=BOOK_SNAPSHOT_PATH),
        _make_silver_entry(data_type="orderbook_delta", path=BOOK_DELTA_PATH),
    )
    rows = _make_decision_rows(row_count)
    requested = frozenset(features) | {"close_return", "high_low_range", "volume"}

    reset_microstructure_file_cache_stats(clear_cache=True)
    print(f"=== Profile : {row_count} rows, features={features} ===")
    print(f"trades_path        : {TRADES_PATH} ({TRADES_PATH.stat().st_size / 1e6:.1f} MB)")
    print(f"book_snapshot_path : {BOOK_SNAPSHOT_PATH} ({BOOK_SNAPSHOT_PATH.stat().st_size / 1e6:.1f} MB)")
    print(f"book_delta_path    : {BOOK_DELTA_PATH} ({BOOK_DELTA_PATH.stat().st_size / 1e6:.1f} MB)")

    profiler = cProfile.Profile()
    t0 = time.perf_counter()
    profiler.enable()
    try:
        overlays, stats = _feature_overlay_batch_from_engine_native_bridge(
            requested_feature_names=requested,
            pair="BTCUSDT",
            timeframe="1m",
            rows=rows,
            entry_trade_entries=trade_entries,
            entry_book_entries=book_entries,
        )
    finally:
        profiler.disable()
    elapsed = time.perf_counter() - t0

    cache_stats = get_microstructure_file_cache_stats()
    print(f"\n=== Result : elapsed={elapsed:.1f}s ===")
    print(f"overlays_returned : {len(overlays)}")
    print(f"batch_status      : {stats.get('batch_status')}")
    print(f"overlay_row_count : {stats.get('overlay_row_count')}")
    print(f"missing_row_count : {stats.get('missing_row_count')}")
    print(f"\n=== Cache stats ===")
    for key in (
        "hit_count",
        "miss_count",
        "rows_loaded",
        "bytes_loaded",
        "cached_file_count",
        "cached_row_count",
        "time_index_hit_count",
        "time_index_miss_count",
    ):
        print(f"  {key:24s} = {cache_stats.get(key)}")

    profile_out = REPO_ROOT / "build" / "profile_a2_gold_microstructure.prof"
    profile_out.parent.mkdir(parents=True, exist_ok=True)
    profiler.dump_stats(str(profile_out))
    print(f"\nProfile written to: {profile_out}")
    print(f"Per-row elapsed   : {elapsed * 1000 / row_count:.1f} ms/row")
    print(f"Extrapolation 1d  : {elapsed * 1440 / row_count / 60:.1f} min for 1440 rows")
    print(f"\n=== Top 25 cumulative hotspots ===")
    stats_obj = pstats.Stats(profiler).strip_dirs().sort_stats("cumulative")
    stats_obj.print_stats(25)


if __name__ == "__main__":
    rows = int(sys.argv[1]) if len(sys.argv) >= 2 else 60
    feats = tuple(sys.argv[2].split(",")) if len(sys.argv) >= 3 else ("vpin",)
    run_profile(row_count=rows, features=feats)
