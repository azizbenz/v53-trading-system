def _configure_stdio() -> None:
    stdout = getattr(sys, "stdout", None)
    if stdout is not None and hasattr(stdout, "reconfigure"):
        stdout.reconfigure(encoding="utf-8", errors="replace")
    stderr = getattr(sys, "stderr", None)
    if stderr is not None and hasattr(stderr, "reconfigure"):
        stderr.reconfigure(encoding="utf-8", errors="replace")


def _now_label() -> str:
    return datetime.now(tz=UTC).strftime("%Y-%m-%d %H:%M:%S UTC")


def _pair_class(pair: str) -> str:
    return "tier_1" if pair in {"BTCUSDT", "ETHUSDT"} else "tier_2"


def _active_engines_for_pair(pair: str) -> tuple[str, ...]:
    engines = []
    for engine_id, pairs in ENGINE_PAIR_MAP.items():
        if pair in pairs:
            engines.append(engine_id.value)
    return tuple(engines)


def _build_demo_pairs():
    cards = []
    for index, pair in enumerate(_COMPLETE_PAIR_ORDER):
        health = PairHealthLevel.HEALTHY
        is_active = True
        suspension_reason = ""
        freshness_ms = 800 + index * 120
        if pair == "MATICUSDT":
            health = PairHealthLevel.STALE
            freshness_ms = 12_000
        elif pair == "NEARUSDT":
            health = PairHealthLevel.SUSPENDED
            is_active = False
            suspension_reason = "governed rollback candidate"

        cards.append(
            collect_pair_metrics(
                pair=pair,
                health=health,
                freshness_ms=freshness_ms,
                backlog_depth=8 + index * 3,
                is_active=is_active,
                average_cost_bps=0.9 + index * 0.08,
                cost_p90_bps=1.3 + index * 0.11,
                ce_expected=0.00065 - index * 0.00003,
                useful_frequency=2.2 - index * 0.09,
                suspension_reason=suspension_reason,
            )
        )
    return tuple(cards)


